import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { build } from 'esbuild';

const repositoryRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '..',
);
const entryPoint = path.join(
  repositoryRoot,
  'scripts',
  'media-mcp',
  'server-entry.mjs',
);
const destination = path.join(
  repositoryRoot,
  'plugins',
  'ergouzi-media-mcp',
  'scripts',
  'server.mjs',
);
const licensesDestination = path.join(
  repositoryRoot,
  'plugins',
  'ergouzi-media-mcp',
  'THIRD_PARTY_LICENSES.txt',
);
const manifest = JSON.parse(
  await readFile(
    path.join(
      repositoryRoot,
      'plugins',
      'ergouzi-media-mcp',
      '.codex-plugin',
      'plugin.json',
    ),
    'utf8',
  ),
);
const checkOnly = process.argv.includes('--check');
const temporary = checkOnly
  ? await mkdtemp(path.join(os.tmpdir(), 'ergouzi-media-mcp-build-'))
  : null;
const outfile = temporary ? path.join(temporary, 'server.mjs') : destination;
const licensesOutfile = temporary
  ? path.join(temporary, 'THIRD_PARTY_LICENSES.txt')
  : licensesDestination;

function packageNameFromInput(input) {
  const normalized = input.replaceAll('\\', '/');
  const marker = 'node_modules/';
  const index = normalized.lastIndexOf(marker);
  if (index === -1) return null;
  const parts = normalized.slice(index + marker.length).split('/');
  return parts[0]?.startsWith('@') ? parts.slice(0, 2).join('/') : parts[0];
}

async function renderThirdPartyLicenses(packageNames) {
  const sections = [
    'THIRD-PARTY SOFTWARE LICENSES',
    '',
    'Generated by npm run build:media-mcp from the packages included in scripts/server.mjs.',
  ];
  for (const packageName of packageNames) {
    const packageRoot = path.join(repositoryRoot, 'node_modules', packageName);
    const metadata = JSON.parse(
      await readFile(path.join(packageRoot, 'package.json'), 'utf8'),
    );
    const license = await readFile(path.join(packageRoot, 'LICENSE'), 'utf8');
    sections.push(
      '',
      '='.repeat(78),
      `${packageName}@${metadata.version}`,
      `License: ${metadata.license}`,
      '='.repeat(78),
      '',
      license.trimEnd(),
    );
  }
  return `${sections.join('\n')}\n`;
}

try {
  const buildResult = await build({
    absWorkingDir: repositoryRoot,
    banner: {
      js: '// Generated by npm run build:media-mcp. Do not edit directly.',
    },
    bundle: true,
    charset: 'utf8',
    define: {
      __ERGOUZI_MEDIA_MCP_VERSION__: JSON.stringify(manifest.version),
    },
    entryPoints: [path.relative(repositoryRoot, entryPoint)],
    format: 'esm',
    legalComments: 'eof',
    logLevel: 'silent',
    metafile: true,
    outfile,
    platform: 'node',
    target: 'node22',
  });
  const packageNames = [
    ...new Set(
      Object.keys(buildResult.metafile.inputs)
        .map(packageNameFromInput)
        .filter(Boolean),
    ),
  ].sort();
  await writeFile(
    licensesOutfile,
    await renderThirdPartyLicenses(packageNames),
    'utf8',
  );

  if (checkOnly) {
    const [expected, actual, expectedLicenses, actualLicenses] =
      await Promise.all([
        readFile(destination),
        readFile(outfile),
        readFile(licensesDestination),
        readFile(licensesOutfile),
      ]);
    if (!expected.equals(actual) || !expectedLicenses.equals(actualLicenses))
      throw new Error(
        'Generated media MCP artifacts are stale; run npm run build:media-mcp',
      );
  }
} finally {
  if (temporary) await rm(temporary, { recursive: true, force: true });
}
